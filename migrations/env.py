"""Alembic environment.

Two decisions here that are hard to change later.

**The URL comes from application settings, not from ``alembic.ini``.** If the URL lived
in the ini file, there would be two sources of truth for which database this project
talks to, and the interesting failure -- migrating one database while the application
reads another -- produces no error at all, just a table that mysteriously does not
exist. Reading ``DATABASE_URL`` through :func:`medguard.config.get_settings` means the
app and its migrations cannot disagree.

**``render_as_batch=True``, from the very first migration.** SQLite implements almost
none of ``ALTER TABLE``: you cannot drop a column, alter a type, or add most
constraints. Alembic's batch mode works around this by creating a new table, copying
the rows, dropping the original and renaming -- but it has to be switched on *before*
the migrations that need it are written. Retrofitting it means rewriting history. It is
harmless on PostgreSQL, which supports real ``ALTER TABLE``, so it is set
unconditionally rather than per-dialect.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

# Importing the Database module registers every table on Base.metadata. Autogenerate
# compares against that, so a table whose module was never imported is invisible to it
# and would be silently dropped by the next autogenerated migration.
from medguard.config import get_settings
from medguard.storage.database import metadata as target_metadata

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)


def _database_url() -> str:
    """The one URL both the application and its migrations use."""
    return get_settings().app.database_url


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting.

    Used to hand a DBA the exact DDL for review before it touches a real database.
    """
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        render_as_batch=True,
        compare_type=True,
        compare_server_default=True,
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Connect and apply migrations."""
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = _database_url()

    connectable = engine_from_config(
        section,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            render_as_batch=True,
            # Without these, autogenerate ignores column type and default changes and
            # produces migrations that silently omit them.
            compare_type=True,
            compare_server_default=True,
        )

        with context.begin_transaction():
            context.run_migrations()

    connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
