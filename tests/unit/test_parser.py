"""PDF extraction, and the ways a PDF fails to be one.

The failure tests carry most of the weight here. A corpus is downloaded from the public
internet, and "PDF" describes bytes that arrived with a content type, not bytes that
parse: publishers serve consent interstitials, WAF challenge pages and truncated
transfers under a `.pdf` URL. Each of those has to become one failed document with a
readable reason, never a traceback that takes the other nineteen down with it.

Everything here is offline. The fixtures are generated by `tests/fixtures/make_pdf.py`
at test time, so there is no committed binary anyone has to trust.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from medguard.errors import IngestionError, ParseError
from medguard.ingestion import parser
from medguard.ingestion.parser import PageText, parse, to_one_based_page
from tests.fixtures.make_pdf import (
    RUNNING_FOOTER,
    RUNNING_HEADER,
    SYNTHETIC_VERSIONS,
    write_structured_pdf,
    write_synthetic_pdf,
)


@pytest.fixture
def three_page_pdf(tmp_path: Path) -> Path:
    return write_synthetic_pdf(tmp_path / "three.pdf", SYNTHETIC_VERSIONS[0], pages=3)


@pytest.fixture
def structured_pdf(tmp_path: Path) -> Path:
    return write_structured_pdf(tmp_path / "structured.pdf", pages=5)


class TestPageNumbering:
    """The one conversion between PyMuPDF's 0-based index and a citable page."""

    def test_the_first_page_is_page_one(self) -> None:
        assert to_one_based_page(0) == 1

    def test_the_fifth_index_is_page_five(self) -> None:
        assert to_one_based_page(4) == 5

    def test_a_negative_index_is_rejected(self) -> None:
        """Not a page at all; silently returning 0 would defeat the point."""
        with pytest.raises(ValueError, match="must be >= 0"):
            to_one_based_page(-1)

    def test_extracted_pages_are_numbered_from_one(self, three_page_pdf: Path) -> None:
        numbers = [page.page_number for page in parse(three_page_pdf).pages()]
        assert numbers == [1, 2, 3]

    def test_no_page_is_ever_page_zero(self, structured_pdf: Path) -> None:
        """The database rejects page 0; the parser must never try to write one."""
        assert all(page.page_number >= 1 for page in parse(structured_pdf).pages())


class TestExtraction:
    def test_the_page_count_is_reported_before_iterating(self, three_page_pdf: Path) -> None:
        assert parse(three_page_pdf).page_count == 3

    def test_every_page_yields_a_page_text(self, three_page_pdf: Path) -> None:
        pages = list(parse(three_page_pdf).pages())
        assert len(pages) == 3
        assert all(isinstance(page, PageText) for page in pages)

    def test_the_text_is_actually_the_document_text(self, structured_pdf: Path) -> None:
        """A parser that returns empty strings passes any test that only counts pages."""
        first = next(parse(structured_pdf).pages())
        assert "Section 1. Scope" in first.text

    def test_char_count_matches_the_text(self, three_page_pdf: Path) -> None:
        assert all(page.char_count == len(page.text) for page in parse(three_page_pdf).pages())

    def test_a_running_header_lands_in_the_top_band(self, structured_pdf: Path) -> None:
        """The cleaner cannot strip furniture the parser did not mark as furniture."""
        first = next(parse(structured_pdf).pages())
        assert any(RUNNING_HEADER in block.text for block in first.top_blocks)

    def test_a_running_footer_lands_in_the_bottom_band(self, structured_pdf: Path) -> None:
        first = next(parse(structured_pdf).pages())
        expected = RUNNING_FOOTER.format(page=1, total=5)
        assert any(expected in block.text for block in first.bottom_blocks)

    def test_body_text_is_not_mistaken_for_a_band(self, structured_pdf: Path) -> None:
        """Bands are position-based; a body paragraph must not appear in one."""
        first = next(parse(structured_pdf).pages())
        banded = " ".join(b.text for b in (*first.top_blocks, *first.bottom_blocks))
        assert "Paragraph 1 of section" not in banded

    def test_the_bands_stay_small(self, structured_pdf: Path) -> None:
        """ "Do not over-return": a band is a running head, not half the page."""
        for page in parse(structured_pdf).pages():
            assert len(page.top_blocks) <= 3
            assert len(page.bottom_blocks) <= 3


class TestLaziness:
    def test_parse_extracts_nothing_on_its_own(
        self, three_page_pdf: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        calls = _count_extractions(monkeypatch)
        parse(three_page_pdf)
        assert calls == []

    def test_creating_the_iterator_extracts_nothing(
        self, three_page_pdf: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        document = parse(three_page_pdf)
        calls = _count_extractions(monkeypatch)
        document.pages()  # generator created, not advanced
        assert calls == []

    def test_pages_are_extracted_one_at_a_time(
        self, three_page_pdf: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The property that keeps a 400-page document off the heap all at once."""
        document = parse(three_page_pdf)
        calls = _count_extractions(monkeypatch)

        stream = document.pages()
        next(stream)
        assert calls == [1]
        next(stream)
        assert calls == [1, 2]

    def test_abandoning_the_iterator_releases_the_file(self, tmp_path: Path) -> None:
        """On Windows an unclosed handle makes the file undeletable, not merely leaked."""
        path = write_synthetic_pdf(tmp_path / "held.pdf", SYNTHETIC_VERSIONS[0], pages=3)
        stream = parse(path).pages()
        next(stream)
        del stream

        path.unlink()  # raises PermissionError if the document is still open
        assert not path.exists()


def _count_extractions(monkeypatch: pytest.MonkeyPatch) -> list[int]:
    """Record the page number of every extraction, in order."""
    seen: list[int] = []
    original = parser._extract_page_text

    def spy(page: object, page_number: int) -> PageText:
        seen.append(page_number)
        return original(page, page_number)

    monkeypatch.setattr(parser, "_extract_page_text", spy)
    return seen


class TestFailures:
    """Every one of these is a real thing a public-health PDF URL has returned."""

    def test_a_missing_file_raises_parse_error(self, tmp_path: Path) -> None:
        with pytest.raises(ParseError, match=r"absent\.pdf"):
            parse(tmp_path / "absent.pdf")

    def test_an_empty_file_raises_parse_error(self, tmp_path: Path) -> None:
        path = tmp_path / "empty.pdf"
        path.write_bytes(b"")
        with pytest.raises(ParseError, match=r"empty\.pdf"):
            parse(path)

    def test_a_truncated_pdf_raises_parse_error(self, three_page_pdf: Path, tmp_path: Path) -> None:
        """A transfer cut off mid-file: valid header, unusable body."""
        broken = tmp_path / "truncated.pdf"
        broken.write_bytes(three_page_pdf.read_bytes()[:400])
        with pytest.raises(ParseError, match=r"truncated\.pdf"):
            parse(broken)

    def test_an_html_error_page_raises_parse_error(self, tmp_path: Path) -> None:
        """The WAF challenge case, and the nastiest one in this list.

        PyMuPDF opens HTML happily and extracts "Are you a robot?" as page text. With no
        format check the pipeline would chunk it, embed it, and serve it to a clinician
        as content attributed to the CDC. It fails here instead.
        """
        path = tmp_path / "consent.pdf"
        path.write_bytes(b"<html><body>Are you a robot?</body></html>" * 400)
        with pytest.raises(ParseError, match="not PDF"):
            parse(path)

    def test_a_zero_page_pdf_raises_rather_than_yielding_nothing(self, tmp_path: Path) -> None:
        """ "Indexed, 0 chunks" is a document nobody looks at again.

        Hand-written bytes because PyMuPDF refuses to *save* a zero-page document, while
        being perfectly willing to open one. The shape occurs in the wild as a
        placeholder left behind by a publisher who withdrew a document.
        """
        path = tmp_path / "nopages.pdf"
        path.write_bytes(
            b"%PDF-1.4\n"
            b"1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n"
            b"2 0 obj<</Type/Pages/Kids[]/Count 0>>endobj\n"
            b"trailer<</Size 3/Root 1 0 R>>\n"
            b"%%EOF\n"
        )
        with pytest.raises(ParseError, match="no pages"):
            parse(path)

    def test_a_directory_raises_parse_error_not_oserror(self, tmp_path: Path) -> None:
        with pytest.raises(ParseError):
            parse(tmp_path)

    def test_the_error_always_names_the_document(self, tmp_path: Path) -> None:
        """ "Which of the twenty failed?" is the first question, every time."""
        path = tmp_path / "identifiable_name.pdf"
        path.write_bytes(b"not a pdf at all")
        with pytest.raises(ParseError) as caught:
            parse(path)
        assert "identifiable_name.pdf" in caught.value.detail

    def test_parse_error_is_an_ingestion_error(self) -> None:
        """The pipeline catches the base class to isolate one document's failure."""
        assert issubclass(ParseError, IngestionError)

    def test_the_user_message_carries_no_internals(self, tmp_path: Path) -> None:
        path = tmp_path / "x.pdf"
        path.write_bytes(b"nope")
        with pytest.raises(ParseError) as caught:
            parse(path)
        assert "mupdf" not in caught.value.user_message.lower()


class TestPageTextModel:
    def test_page_zero_cannot_be_constructed(self) -> None:
        with pytest.raises(ValueError, match="greater than or equal to 1"):
            PageText(page_number=0, text="x")

    def test_char_count_is_derived_when_omitted(self) -> None:
        assert PageText(page_number=1, text="hello").char_count == 5

    def test_a_lying_char_count_is_rejected(self) -> None:
        with pytest.raises(ValueError, match="char_count"):
            PageText(page_number=1, text="hello", char_count=99)

    def test_it_is_frozen(self) -> None:
        page = PageText(page_number=1, text="hello")
        with pytest.raises(ValueError, match="frozen"):
            page.text = "changed"
